/** Represents a geocoded city or monitoring location with coordinates. */
export interface CityLocation {
  name: string;
  admin1?: string;
  country?: string;
  latitude: number;
  longitude: number;
}

/** Single hourly air quality data point in a 24-hour forecast series. */
export interface HourlyAQIPoint {
  time: string;
  pm2_5: number;
  pm10: number;
  us_aqi: number;
  visibilityKm?: number;
}

/** Current snapshot of particulate concentration, US AQI, and visibility. */
export interface CurrentAQI {
  pm2_5: number;
  pm10: number;
  us_aqi: number;
  time: string;
  category: AQICategory;
  color: string;
  visibilityKm: number;
  visibilityCondition: string;
}

/** Standard US EPA Air Quality Index severity band label. */
export type AQICategory =
  | "Good"
  | "Moderate"
  | "Unhealthy for Sensitive Groups"
  | "Unhealthy"
  | "Very Unhealthy"
  | "Hazardous";

/** Summary outdoor safety verdict derived from current AQI conditions. */
export interface OutdoorVerdict {
  status: "SAFE" | "CAUTION" | "HAZARDOUS" | "STAY_INDOORS";
  headline: string;
  badgeLabel: string;
  badgeColor: string;
  summary: string;
  safeWindowPrompt: string;
  recommendation: string;
}

/** Normalized air quality payload returned by `/api/air-quality` and consumed by the UI. */
export interface ParsedAQIData {
  city: string;
  coordinates: { latitude: number; longitude: number };
  current: CurrentAQI;
  forecast24h: HourlyAQIPoint[];
  outdoorVerdict: OutdoorVerdict;
}

/** User-configured household sensitivity profile used to personalize AI guidance. */
export interface FamilyProfile {
  members: string[];
  commute: "Two-wheeler" | "Public Transit" | "Car" | "Walk/Cycle";
  homeSetup: "Air Purifier" | "Natural Ventilation";
}

/** Recommended lower-exposure outdoor interval from the AI smog plan. */
export interface SafeWindow {
  timeWindow: string;
  pm25Level: number;
  riskLevel: "Low" | "Moderate" | "High" | "Severe";
  bestFor: string;
  why: string;
}

/** Actionable indoor exposure reduction recommendation. */
export interface IndoorHack {
  title: string;
  action: string;
  why: string;
}

/** Commute alternative aimed at lowering direct tailpipe inhalation. */
export interface CommuteSwap {
  recommendation: string;
  why: string;
}

/** Structured family action plan generated by Gemini or epidemiological fallback. */
export interface AISmogPlan {
  headlineSummary: string;
  safeWindows: SafeWindow[];
  indoorHacks: IndoorHack[];
  commuteSwap: CommuteSwap;
}

/** Chat message entry rendered inside the AQIfer Assistant conversation feed. */
export interface ChatMessage {
  id: string;
  role: "user" | "assistant";
  content: string;
  timestamp: string;
}

/** Single spatial point returned by `/api/aqi-grid` for OpenStreetMap overlays. */
export interface AQIGridPoint {
  latitude: number;
  longitude: number;
  us_aqi: number;
  pm2_5: number;
  category: AQICategory;
  color: string;
  label?: string;
}

/** Air quality reading sampled at an individual route waypoint. */
export interface RouteWaypointAQI {
  latitude: number;
  longitude: number;
  us_aqi: number;
  pm2_5: number;
  category: AQICategory;
  color: string;
}

/** Candidate road/bike corridor annotated with aggregated AQI metrics. */
export interface EvaluatedRoute {
  index: number;
  label: string;
  distanceKm: number;
  durationMin: number;
  avgAqi: number;
  maxAqi: number;
  avgPm25: number;
  coordinates: [number, number][];
  waypoints: RouteWaypointAQI[];
  color: string;
}

/** Complete journey air quality safety evaluation returned by `/api/route-safety`. */
export interface RouteSafetyResult {
  origin: { name: string; latitude: number; longitude: number };
  destination: { name: string; latitude: number; longitude: number };
  routes: EvaluatedRoute[];
  recommendedRouteIndex: number;
  verdict: "SAFE" | "CAUTION" | "AVOID";
  verdictHeadline: string;
  analysis: string;
  betterRouteSuggestion: string;
}

/** Two-hour low-PM2.5 window computed from the 24-hour hourly forecast for dashboard display. */
export interface SafeWindowSummary {
  idx: number;
  avgPm: number;
  aqiVal: number;
  label: string;
  day: string;
}
